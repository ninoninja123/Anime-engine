#!/usr/bin/env python3
"""Regenerate showdown/shots_data.js from pre/shots.json (run after any edit of shots.json):  python3 showdown/gen_data.py
   Missing pre/shots.json -> a stub (no shots, SHOW_DUR 180) so the program still loads."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'pre', 'shots.json')
if os.path.exists(src):
    d = json.load(open(src))
else:
    d = {'meta': {'duration': 180, 'characters': {'ITA': 'Itachi Uchiha', 'JUL': 'Julius Novachrono', 'URA': 'Urahara Kisuke', 'DAZ': 'Dazai Osamu', 'KYO': 'Kyoraku Shunsui'}}, 'shots': [], 'subtitles': []}
S = {}
for s in d.get('shots', []):
    imp = s.get('impact')
    if isinstance(imp, list): imp = imp[0] if imp else None
    S[s['id']] = {'t0': s['t0'], 't1': s['t1'], 'render': s.get('render'), 'text': s.get('text'), 'bg': s.get('background') or s.get('bg'),
                  'chars': s.get('chars') or [], 'engine_chars': s.get('engine_chars') or [], 'dialogue': s.get('dialogue') or [], 'masked': s.get('masked'), 'phase': s.get('phase'), 'camera': s.get('camera'), 'move': s.get('move'), 'forms': s.get('forms'), 'fx': s.get('fx'), 'dmg': s.get('dmg'), 'text_style': s.get('text_style'), 'light': s.get('light'), 'rain': s.get('rain'), 'action': s.get('action'), 'inserts': s.get('inserts'),
                  'impact': ({'style': imp['style'], 't': imp.get('t', s['t0']), 'frames': imp.get('frames', 3), 'pattern': imp.get('pattern'), 'burst': bool(imp.get('burst') or 'BURST' in (imp.get('tags') or []))} if imp else None)}
subs = d.get('subtitles', [])
meta = d.get('meta', {})
who = meta.get('characters', {})
order = [s['id'] for s in d.get('shots', [])]
dur = meta.get('duration') or (max([s['t1'] for s in d.get('shots', [])]) if d.get('shots') else 180)
out = '/* AUTO-GENERATED by showdown/gen_data.py from pre/shots.json - do not edit by hand */\n'
out += 'const SHOTS = ' + json.dumps(S, ensure_ascii=False) + ';\n'
out += 'const SHOT_ORDER = ' + json.dumps(order) + ';\n'
out += 'const SUBS = ' + json.dumps(subs, ensure_ascii=False) + ';\n'
out += 'const WHO = ' + json.dumps(who, ensure_ascii=False) + ';\n'
out += 'const SHOW_DUR = ' + json.dumps(dur) + ';\n'
open(os.path.join(here, 'shots_data.js'), 'w').write(out)
print('shots', len(S), 'subs', len(subs), 'dur', dur)
