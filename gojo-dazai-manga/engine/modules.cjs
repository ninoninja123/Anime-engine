// Auto module manifest: scans engine/ for poses_*.js, chars_*.js, fx_*.js, sets_*.js, impact_*.js and writes
// engine/modules.js, which (loaded by scripts.js right after the core modules) document.writes them in this order.
// Called automatically by render.js, lab.js and make_sheets.sh; if you only open index.html in a browser after adding
// a new file, run once:   node modules.cjs
const fs = require('fs'), path = require('path');
const ORDER = ['poses_', 'chars_', 'fx_', 'sets_', 'impact_'];
const LOADER = String.raw`(function(){var b=(document.currentScript&&document.currentScript.src||'').replace(/modules\.js.*$/,'');
window.ENGINE_MODULES.forEach(function(f){document.write('<script src="'+b+f+'.js" onerror="console.log(\'missing '+f+'\')"><\/script>');});})();`;
function updateManifest(dir = __dirname) {
  const files = fs.readdirSync(dir).filter(f => /\.js$/.test(f) && ORDER.some(p => f.startsWith(p)) && !/\.(bak|tmp|off)\.js$/.test(f));
  files.sort((a, b) => { const ia = ORDER.findIndex(p => a.startsWith(p)), ib = ORDER.findIndex(p => b.startsWith(p)); return ia - ib || a.localeCompare(b); });
  const mods = files.map(f => f.replace(/\.js$/, ''));
  const txt = '/* AUTO-GENERATED by modules.cjs - do not edit. Extension modules loaded after the core engine. */\nwindow.ENGINE_MODULES = ' + JSON.stringify(mods) + ';\n' + LOADER + '\n';
  const out = path.join(dir, 'modules.js');
  let old = ''; try { old = fs.readFileSync(out, 'utf8'); } catch (e) {}
  if (old !== txt) { try { fs.writeFileSync(out + '.tmp', txt); fs.renameSync(out + '.tmp', out); } catch (e) {} }
  return mods;
}
module.exports = { updateManifest };
if (require.main === module) console.log(updateManifest().join('\n') || '(no extension modules)');
