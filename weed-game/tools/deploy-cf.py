#!/usr/bin/env python3
"""Julkaisee weed-gamen Cloudflare Workeriksi (https://weed-game.<alidomain>.workers.dev/).

Rakenne (mitattu: dist/ ~7 MB, josta Epidemic-äänet ~5.8 MB -> ei mahdu ilmaistilin ~3 MB worker-rajaan):
  * kaikki dist/-tiedostot ladataan Workers KV:hen sisältöosoitteisina avaimina (sha256), vain uudet/muuttuneet
  * worker.js sisältää vain pienen manifestin {polku: [content-type, kv-avain, koko]} ja palvelee tiedostot
    KV:stä oikeilla Content-Type-, Cache-Control-, ETag- ja Range-otsikoilla (iOS Safari vaatii Rangen äänelle)
  * reunavälimuisti (caches.default) vähentää KV-lukuja

Huom: public/audio/ (Epidemic Sound) on .gitignoressa -> aja tämä samassa ympäristössä, jossa äänet ovat.
API-kutsut menevät curlilla api.cloudflare.com:iin; tässä ympäristössä proxy hoitaa autentikoinnin
(muualla: aseta CF_API_TOKEN, jolloin se lisätään Authorization-otsikkoon). Ei salaisuuksia tiedostossa.

Käyttö:  npm run build && python3 tools/deploy-cf.py [--account ID] [--script weed-game] [--dry-run]
"""
import argparse, hashlib, json, mimetypes, os, subprocess, sys, tempfile

ACCOUNT = '44ae83ec201f2747ef803236274f9ed4'
SCRIPT = 'weed-game'
NS_TITLE = 'weed-game-assets'
API = 'https://api.cloudflare.com/client/v4'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, 'dist')

TYPES = {'.html': 'text/html; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
         '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.glb': 'model/gltf-binary',
         '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.m4a': 'audio/mp4', '.wav': 'audio/wav', '.png': 'image/png',
         '.jpg': 'image/jpeg', '.webp': 'image/webp', '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.txt': 'text/plain; charset=utf-8'}


def curl(args, data_file=None):
    cmd = ['curl', '-sS', '--retry', '3', '--retry-delay', '2']
    tok = os.environ.get('CF_API_TOKEN')
    if tok:
        cmd += ['-H', 'Authorization: Bearer ' + tok]
    cmd += args
    out = subprocess.run(cmd, capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit('curl failed: ' + out.stderr)
    try:
        d = json.loads(out.stdout)
    except json.JSONDecodeError:
        raise SystemExit('bad response: ' + out.stdout[:400])
    if not d.get('success', False):
        raise SystemExit('API error: ' + json.dumps(d.get('errors'))[:600])
    return d


def namespace(account):
    d = curl([f'{API}/accounts/{account}/storage/kv/namespaces?per_page=100'])
    for ns in d['result']:
        if ns['title'] == NS_TITLE:
            return ns['id']
    d = curl(['-X', 'POST', f'{API}/accounts/{account}/storage/kv/namespaces', '-H', 'Content-Type: application/json',
              '--data', json.dumps({'title': NS_TITLE})])
    print('created KV namespace', d['result']['id'])
    return d['result']['id']


def existing_keys(account, ns):
    keys, cursor = set(), ''
    while True:
        d = curl([f'{API}/accounts/{account}/storage/kv/namespaces/{ns}/keys?limit=1000' + (f'&cursor={cursor}' if cursor else '')])
        keys.update(k['name'] for k in d['result'])
        cursor = (d.get('result_info') or {}).get('cursor')
        if not cursor:
            return keys


WORKER = r'''// generated by tools/deploy-cf.py – serves the static build from Workers KV
const M = __MANIFEST__;
const VERSION = "__VERSION__";
function cacheControl(p) {
  if (p === '/sw.js') return 'no-cache';                     // service worker: always revalidated (ETag -> 304)
  if (p === '/index.html' || p.endsWith('.json') || p.endsWith('.webmanifest')) return 'public, max-age=60, must-revalidate';
  if (p.startsWith('/assets/')) return 'public, max-age=31536000, immutable';
  return 'public, max-age=86400';
}
export default {
  async fetch(req, env, ctx) {
    if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    const url = new URL(req.url);
    let p = decodeURIComponent(url.pathname);
    if (p.endsWith('/')) p += 'index.html';
    let e = M[p];
    if (!e && !p.includes('.', p.lastIndexOf('/'))) { p = '/index.html'; e = M[p]; }
    if (!e) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    const [type, key, size] = e;
    const etag = '"' + key.slice(0, 32) + '"';
    const base = { 'content-type': type, 'cache-control': cacheControl(p), 'etag': etag, 'accept-ranges': 'bytes',
                   'x-content-type-options': 'nosniff', 'access-control-allow-origin': '*' };
    const inm = req.headers.get('if-none-match');          // may be a list and/or weak (W/"...") after proxies/compression
    if (inm && (inm.trim() === '*' || inm.split(',').some(t => t.trim().replace(/^W\//, '') === etag))) return new Response(null, { status: 304, headers: base });
    const cache = caches.default;
    const ckey = new Request(url.origin + '/__kv/' + key);
    let body = null;
    const hit = await cache.match(ckey);
    if (hit) body = await hit.arrayBuffer();
    else {
      body = await env.ASSETS.get(key, { type: 'arrayBuffer' });
      if (!body) return new Response('Asset missing', { status: 502 });
      ctx.waitUntil(cache.put(ckey, new Response(body, { headers: { 'cache-control': 'public, max-age=31536000' } })));
    }
    const range = req.headers.get('range');
    if (range) {
      const m = /bytes=(\d*)-(\d*)/.exec(range);
      if (m) {
        let start = m[1] === '' ? size - Number(m[2]) : Number(m[1]);
        let end = m[1] !== '' && m[2] !== '' ? Number(m[2]) : size - 1;
        if (start < 0) start = 0;
        if (end >= size) end = size - 1;
        if (start > end || start >= size) return new Response(null, { status: 416, headers: { ...base, 'content-range': `bytes */${size}` } });
        const part = body.slice(start, end + 1);
        return new Response(req.method === 'HEAD' ? null : part, { status: 206, headers: { ...base, 'content-range': `bytes ${start}-${end}/${size}`, 'content-length': String(end - start + 1) } });
      }
    }
    return new Response(req.method === 'HEAD' ? null : body, { status: 200, headers: { ...base, 'content-length': String(size), 'x-build': VERSION } });
  },
};
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--account', default=os.environ.get('CF_ACCOUNT_ID', ACCOUNT))
    ap.add_argument('--script', default=SCRIPT)
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    if not os.path.isfile(os.path.join(DIST, 'index.html')):
        raise SystemExit('dist/ missing: run npm run build first')

    files = []
    for root, _, names in os.walk(DIST):
        for n in sorted(names):
            full = os.path.join(root, n)
            rel = '/' + os.path.relpath(full, DIST).replace(os.sep, '/')
            data = open(full, 'rb').read()
            ext = os.path.splitext(n)[1].lower()
            ctype = TYPES.get(ext) or mimetypes.guess_type(n)[0] or 'application/octet-stream'
            key = hashlib.sha256(data).hexdigest()
            files.append((rel, ctype, key, len(data), full))
    total = sum(f[3] for f in files)
    audio = [f for f in files if f[0].startswith('/audio/') and f[0].endswith('.mp3')]
    print(f'{len(files)} files, {total / 1e6:.2f} MB ({len(audio)} audio files, {sum(f[3] for f in audio) / 1e6:.2f} MB)')
    if not audio:
        print('WARNING: no audio in dist/ – public/audio/*.mp3 missing in this environment (they are git-ignored)')
    manifest = {f[0]: [f[1], f[2], f[3]] for f in files}
    version = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()[:12]
    if a.dry_run:
        print(json.dumps(manifest, indent=1)[:2000]); return

    ns = namespace(a.account)
    have = existing_keys(a.account, ns)
    up = [f for f in files if f[2] not in have]
    print(f'KV namespace {ns}: {len(have)} keys present, uploading {len(up)}')
    for rel, ctype, key, size, full in up:
        curl(['-X', 'PUT', f'{API}/accounts/{a.account}/storage/kv/namespaces/{ns}/values/{key}',
              '-H', 'Content-Type: application/octet-stream', '--data-binary', '@' + full])
        print(f'  up {rel} ({size / 1024:.0f} kB)')

    src = WORKER.replace('__MANIFEST__', json.dumps(manifest, separators=(',', ':'))).replace('__VERSION__', version)
    meta = {'main_module': 'worker.js', 'compatibility_date': '2026-11-01',
            'bindings': [{'type': 'kv_namespace', 'name': 'ASSETS', 'namespace_id': ns}]}
    with tempfile.TemporaryDirectory() as td:
        wp = os.path.join(td, 'worker.js'); open(wp, 'w').write(src)
        mp = os.path.join(td, 'meta.json'); open(mp, 'w').write(json.dumps(meta))
        curl(['-X', 'PUT', f'{API}/accounts/{a.account}/workers/scripts/{a.script}',
              '-F', f'metadata=@{mp};type=application/json',
              '-F', f'worker.js=@{wp};type=application/javascript+module;filename=worker.js'])
    print(f'worker "{a.script}" deployed (build {version}, script {len(src) / 1024:.1f} kB)')

    # remove KV keys no longer referenced (old builds)
    stale = have - {f[2] for f in files}
    if stale:
        body = json.dumps(sorted(stale))
        try:
            curl(['-X', 'POST', f'{API}/accounts/{a.account}/storage/kv/namespaces/{ns}/bulk/delete', '-H', 'Content-Type: application/json', '--data', body])
            print(f'removed {len(stale)} stale KV keys')
        except SystemExit as e:
            print('note: stale key cleanup failed:', e)


if __name__ == '__main__':
    main()
