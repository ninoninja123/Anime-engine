/** Arvioi repliikin kesto (s), kun äänitiedostoa ei ole. */
export function estimateDuration(line) {
  const en = line.en.length * 0.058, ja = [...line.ja].length * 0.16;
  return Math.max(1.4, Math.min(7, Math.max(en, ja)));
}
